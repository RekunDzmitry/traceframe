#!/usr/bin/env node
// Scans ~/.claude/projects/*/memory/*.md and writes memory-data.js — a window-attached
// graph of nodes (memories + project hubs) and edges (project membership + cross-references).

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const PROJECTS_DIR = join(homedir(), '.claude', 'projects');
const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(HERE, '..', 'memory-data.js');

async function listDirs(dir) {
  try {
    const entries = await readdir(dir, { withFileTypes: true });
    return entries.filter((e) => e.isDirectory()).map((e) => e.name);
  } catch {
    return [];
  }
}

async function listMdFiles(dir) {
  try {
    const entries = await readdir(dir, { withFileTypes: true });
    return entries.filter((e) => e.isFile() && e.name.endsWith('.md')).map((e) => e.name);
  } catch {
    return [];
  }
}

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) {
      let val = kv[2].trim();
      if (val.startsWith('"') && val.endsWith('"')) val = val.slice(1, -1);
      if (val.startsWith("'") && val.endsWith("'")) val = val.slice(1, -1);
      meta[kv[1]] = val;
    }
  }
  return { meta, body: text.slice(m[0].length) };
}

function projectLabel(folderName) {
  // -Users-dzmitryrekun-github-parallel → parallel
  // -Users-dzmitryrekun-github-voice-bird-desktop--claude-worktrees-fix-energy-consumption → voice-bird-desktop (worktree: fix-energy-consumption)
  const wt = folderName.split('--claude-worktrees-');
  const main = wt[0].replace(/^-/, '').split('-');
  // Drop "Users", "<username>", "github" prefix if present
  const drop = ['Users', 'github'];
  let i = 0;
  while (i < main.length && (drop.includes(main[i]) || main[i].toLowerCase() === 'users')) i++;
  if (i < main.length) i++; // drop username token after "Users"
  const tail = main.slice(i).join('-') || folderName;
  if (wt[1]) return `${tail} ⌥ ${wt[1]}`;
  return tail;
}

const folders = await listDirs(PROJECTS_DIR);
const projects = [];
const memories = [];

for (const folder of folders) {
  const memDir = join(PROJECTS_DIR, folder, 'memory');
  const files = await listMdFiles(memDir);
  if (!files.length) continue;
  const projId = `proj:${folder}`;
  const label = projectLabel(folder);
  const projMems = [];
  for (const f of files) {
    if (f === 'MEMORY.md') continue;
    const text = await readFile(join(memDir, f), 'utf8');
    const { meta, body } = parseFrontmatter(text);
    const id = `mem:${folder}:${f}`;
    memories.push({
      id,
      file: f,
      project: folder,
      projectLabel: label,
      name: meta.name || f.replace(/\.md$/, ''),
      description: meta.description || '',
      type: meta.type || 'unknown',
      body: body.trim(),
    });
    projMems.push(id);
  }
  if (projMems.length) {
    projects.push({ id: projId, label, folder, memberIds: projMems });
  }
}

// Edges
const edges = [];
for (const p of projects) {
  for (const mid of p.memberIds) edges.push({ source: mid, target: p.id, kind: 'member' });
}
// Cross-references: memory A's body mentions memory B's title (case-insensitive)
for (const a of memories) {
  const aBody = a.body.toLowerCase();
  for (const b of memories) {
    if (a.id === b.id) continue;
    if (b.name.length < 6) continue;
    if (aBody.includes(b.name.toLowerCase())) {
      edges.push({ source: a.id, target: b.id, kind: 'mentions' });
    }
  }
}

const nodes = [
  ...projects.map((p) => ({
    id: p.id,
    label: p.label,
    kind: 'project',
    folder: p.folder,
    memberCount: p.memberIds.length,
  })),
  ...memories.map((m) => ({
    id: m.id,
    label: m.name,
    kind: 'memory',
    type: m.type,
    description: m.description,
    body: m.body,
    file: m.file,
    project: m.project,
    projectLabel: m.projectLabel,
  })),
];

const out = `// Auto-generated by bin/scan-memories.mjs
// Source: ${PROJECTS_DIR}
// Generated: ${new Date().toISOString()}
// To regenerate: node bin/scan-memories.mjs
window.MEMORY_GRAPH = ${JSON.stringify({ nodes, edges }, null, 2)};
`;

await writeFile(OUT_PATH, out);
console.log(
  `[memory-graph] ${nodes.length} nodes (${projects.length} projects, ${memories.length} memories), ${edges.length} edges → ${OUT_PATH}`
);
